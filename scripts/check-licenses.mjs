#!/usr/bin/env node
/**
 * Licence gate (section 2 / section 9 risk): every production dependency must use a licence on the
 * allow-list. Dev-only tools (test runners, linters) are not shipped and are not checked.
 * Reads package-lock.json only — no network, no extra dependencies. Also writes LICENSES.md.
 */
import fs from 'node:fs';

const ALLOW = new Set([
  'MIT',
  'MIT-0',
  'Apache-2.0',
  'BSD-2-Clause',
  'BSD-3-Clause',
  'ISC',
  '0BSD',
  'CC0-1.0',
  'Unlicense',
  'BlueOak-1.0.0',
  'OFL-1.1',
  'Python-2.0',
  'Zlib',
]);

const lock = JSON.parse(fs.readFileSync('package-lock.json', 'utf8'));
const rows = [];
const bad = [];

for (const [key, info] of Object.entries(lock.packages)) {
  if (!key || info.dev || info.devOptional) continue;
  const name = key.replace(/^.*node_modules\//, '');
  let license = info.license;
  if (!license) {
    try {
      const pj = JSON.parse(fs.readFileSync(`${key}/package.json`, 'utf8'));
      license = pj.license ?? (Array.isArray(pj.licenses) ? pj.licenses.map((l) => l.type).join(' OR ') : undefined);
    } catch {
      /* not installed (optional platform package) */
    }
  }
  license = typeof license === 'object' ? license?.type : license;
  const ids = String(license ?? 'UNKNOWN')
    .replace(/[()]/g, '')
    .split(/\s+(?:OR|AND)\s+/);
  const isOr = /\bOR\b/.test(String(license));
  const ok = isOr ? ids.some((l) => ALLOW.has(l)) : ids.every((l) => ALLOW.has(l));
  rows.push({ name, version: info.version, license: license ?? 'UNKNOWN' });
  if (!ok) bad.push(`${name}@${info.version}: ${license ?? 'UNKNOWN'}`);
}

rows.sort((a, b) => a.name.localeCompare(b.name));
const md = [
  '# Third-party licences',
  '',
  'Production dependencies bundled into DevToolkit, generated by `npm run licenses`. All are on the permissive allow-list',
  `(${[...ALLOW].join(', ')}).`,
  '',
  '| Package | Version | Licence |',
  '| --- | --- | --- |',
  ...rows.map((r) => `| ${r.name} | ${r.version} | ${r.license} |`),
  '',
].join('\n');
fs.writeFileSync('LICENSES.md', md);

if (bad.length) {
  console.error(`Licence check FAILED — ${bad.length} package(s) not on the allow-list:\n  ${bad.join('\n  ')}`);
  process.exit(1);
}
console.log(`Licence check passed: ${rows.length} production packages, all permissive. LICENSES.md updated.`);
